package dev.sid.fiveberinspector;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.security.GeneralSecurityException;
import java.util.Arrays;
import java.util.Objects;

/**
 * Strict Android 11+ pairing state machine, run ONLY inside an already-established
 * TLS channel. TLS exporter, native SPAKE2 and AES-GCM come from an independently
 * reviewed authenticated-transport provider, not from this class.
 *
 * No network dialing, ADB commands, settings changes or logging are possible.
 * A successful exchange does NOT authorize access to adbd's STLS connect port.
 */
final class OnDeviceAdbPairingExchange {
    static final int TLS_EXPORTER_LENGTH = 64;
    static final int SPAKE2_MESSAGE_LENGTH = 32;
    static final int PEER_INFO_LENGTH = OnDeviceAdbPairingFrame.MAX_PEER_INFO_BYTES;
    static final int PEER_INFO_CIPHERTEXT_LENGTH = PEER_INFO_LENGTH + 16; // AES-GCM tag
    static final int CLIENT_PEER_TYPE = 0; // ADB RSA public key

    interface Crypto extends AutoCloseable {
        byte[] firstMessage() throws GeneralSecurityException;
        boolean acceptPeerMessage(byte[] message) throws GeneralSecurityException;
        byte[] seal(byte[] plain) throws GeneralSecurityException;
        byte[] open(byte[] cipher) throws GeneralSecurityException;
        @Override void close(); // must clear native state and ephemeral secrets
    }

    interface CryptoFactory {
        /** Copy input if needed: owner zeros password immediately after return. */
        Crypto create(byte[] password) throws GeneralSecurityException;
    }

    private OnDeviceAdbPairingExchange() {}

    /** Pairing codes are exactly 6 ASCII digits. Do not log or persist them. */
    static boolean validCode(char[] code) {
        if (code == null || code.length != 6) return false;
        for (char c : code) if (c < '0' || c > '9') return false;
        return true;
    }

    /** Password = 6 ASCII pairing digits + 64 bytes from the TLS exporter. */
    static byte[] sessionPassword(char[] code, byte[] exporter) throws IOException {
        if (!validCode(code) || exporter == null || exporter.length != TLS_EXPORTER_LENGTH)
            throw new IOException("Invalid ADB pairing input");
        byte[] password = new byte[6 + TLS_EXPORTER_LENGTH];
        for (int i = 0; i < 6; i++) password[i] = (byte) code[i];
        System.arraycopy(exporter, 0, password, 6, TLS_EXPORTER_LENGTH);
        return password;
    }

    /** Wire PeerInfo: type(1) + ADB public key bytes(8191), zero padded. */
    static byte[] publicKeyInfo(byte[] adbPublicKey) throws IOException {
        if (adbPublicKey == null || adbPublicKey.length < 2 || adbPublicKey.length >= PEER_INFO_LENGTH
                || adbPublicKey[adbPublicKey.length - 1] != 0)
            throw new IOException("Invalid ADB public identity");
        byte[] data = new byte[PEER_INFO_LENGTH];
        System.arraycopy(adbPublicKey, 0, data, 1, adbPublicKey.length);
        // Must contain a NUL-terminated ADB public key, never a private key.
        return data;
    }

    /**
     * Perform the pairing exchange over an existing TLS session.
     * The caller must supply an exporter from that *same* TLS socket, not from
     * a different connection or randomly generated bytes. Timeout and peer
     * certificate / identity policy belong to the TLS transport provider.
     * This method does not retain the pairing code or exporter.
     */
    static String exchange(InputStream inbound, OutputStream outbound, char[] code,
                         byte[] tlsExporter, byte[] adbPublicKey, CryptoFactory factory)
            throws IOException, GeneralSecurityException {
        Objects.requireNonNull(inbound);
        Objects.requireNonNull(outbound);
        Objects.requireNonNull(factory);
        byte[] password = sessionPassword(code, tlsExporter);
        Crypto crypto;
        try { crypto = Objects.requireNonNull(factory.create(password)); }
        finally { Arrays.fill(password, (byte) 0); }
        try (Crypto session = crypto) {
            byte[] first = session.firstMessage();
            try {
                if (first == null || first.length != SPAKE2_MESSAGE_LENGTH)
                    throw new IOException("Invalid SPAKE2 message");
                OnDeviceAdbPairingFrame.write(outbound, OnDeviceAdbPairingFrame.TYPE_SPAKE2, first);
            } finally { if (first != null) Arrays.fill(first, (byte) 0); }

            try (OnDeviceAdbPairingFrame received = OnDeviceAdbPairingFrame.read(inbound)) {
                if (received.type != OnDeviceAdbPairingFrame.TYPE_SPAKE2
                        || received.payload.length != SPAKE2_MESSAGE_LENGTH
                        || !session.acceptPeerMessage(received.payload))
                    throw new IOException("ADB pairing authentication rejected");
            }

            byte[] plain = publicKeyInfo(adbPublicKey);
            byte[] sealed = null;
            try {
                sealed = session.seal(plain);
                if (sealed == null || sealed.length != PEER_INFO_CIPHERTEXT_LENGTH)
                    throw new IOException("Invalid authenticated peer message");
                OnDeviceAdbPairingFrame.write(outbound, OnDeviceAdbPairingFrame.TYPE_PEER_INFO, sealed);
            } finally {
                Arrays.fill(plain, (byte) 0);
                if (sealed != null) Arrays.fill(sealed, (byte) 0);
            }

            try (OnDeviceAdbPairingFrame received = OnDeviceAdbPairingFrame.read(inbound)) {
                if (received.type != OnDeviceAdbPairingFrame.TYPE_PEER_INFO
                        || received.payload.length != PEER_INFO_CIPHERTEXT_LENGTH)
                    throw new IOException("Invalid authenticated peer message");
                byte[] remote = session.open(received.payload);
                try {
                    if (remote == null || remote.length != PEER_INFO_LENGTH
                            || (remote[0] & 0xff) != CLIENT_PEER_TYPE)
                        throw new IOException("ADB pairing peer identity invalid");
                    int end=1;
                    while(end<remote.length && remote[end]!=0)end++;
                    if(end<=1 || end>256 || end==remote.length)
                        throw new IOException("ADB pairing device identity invalid");
                    for(int i=1;i<end;i++) {
                        int c=remote[i]&0xff;
                        if(c<33 || c>126) throw new IOException("Invalid ADB pairing device identity");
                    }
                    return new String(remote,1,end-1,java.nio.charset.StandardCharsets.US_ASCII);
                } finally { if (remote != null) Arrays.fill(remote, (byte) 0); }
            }
        }
    }
}
